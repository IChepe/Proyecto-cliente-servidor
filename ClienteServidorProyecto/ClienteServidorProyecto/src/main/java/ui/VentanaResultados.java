    /** Ancho, color, fuente y alineación de una columna del ranking. */
    private void columna(int indice, int ancho, java.awt.Color color, int estilo, int tamano, int alineacion) {
        javax.swing.table.TableColumn col = tblRanking.getColumnModel().getColumn(indice);
        col.setPreferredWidth(ancho);
        java.awt.Font fuente = new java.awt.Font("Segoe UI", estilo, tamano);
        javax.swing.table.DefaultTableCellRenderer celda = new javax.swing.table.DefaultTableCellRenderer() {
            @Override
            public java.awt.Component getTableCellRendererComponent(javax.swing.JTable t, Object v,
                    boolean sel, boolean foco, int fila, int c) {
                super.getTableCellRendererComponent(t, v, false, false, fila, c);
                setFont(fuente);
                setForeground(color);
                setBackground(t.getBackground());
                setBorder(javax.swing.BorderFactory.createEmptyBorder(0, 20, 0, 20));
                return this;
            }
        };
        celda.setHorizontalAlignment(alineacion);
        col.setCellRenderer(celda);
    }

    /** Aclara un poco el botón al pasar el mouse. */
    private void efectoHover(javax.swing.AbstractButton... botones) {
        for (javax.swing.AbstractButton boton : botones) {
            boton.addMouseListener(new java.awt.event.MouseAdapter() {
                private java.awt.Color base;

                @Override
                public void mouseEntered(java.awt.event.MouseEvent e) {
                    if (boton.isEnabled()) {
                        base = boton.getBackground();
                        boton.setBackground(new java.awt.Color(
                                base.getRed() + (255 - base.getRed()) * 15 / 100,
                                base.getGreen() + (255 - base.getGreen()) * 15 / 100,
                                base.getBlue() + (255 - base.getBlue()) * 15 / 100));
                    }
                }

                @Override
                public void mouseExited(java.awt.event.MouseEvent e) {
                    if (base != null) {
                        boton.setBackground(base);
                        base = null;
                    }
                }
            });
        }
    }

